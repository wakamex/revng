"""
Write a Python module defining SOURCE_ID, an identifier of the content of a
source tree.

usage: write-source-id.py SOURCE_DIR BUILD_DIR OUTPUT...

For a git checkout SOURCE_ID is "git-tree-<hash of HEAD's tree>". If tracked
files differ from HEAD or untracked, non-ignored files exist outside BUILD_DIR,
"-dirty-<hash>" is appended, where the hash covers the diff and the untracked
files' names and contents; Python bytecode is not counted. Without git metadata
SOURCE_ID is "".

Outputs are rewritten only when their content changes, so a build that leaves the
source unchanged does not rebuild what depends on them.
"""

import hashlib
import subprocess
import sys
from pathlib import Path


def git(directory: Path, *args: str) -> bytes:
    return subprocess.run(
        ["git", "-C", str(directory), *args], check=True, capture_output=True
    ).stdout


def source_id(source: Path, build: Path) -> str:
    try:
        top = Path(git(source, "rev-parse", "--show-toplevel").decode().strip())
        tree = git(top, "rev-parse", "HEAD^{tree}").decode().strip()
        diff = git(top, "diff", "--binary", "HEAD")
        untracked = git(
            top,
            "ls-files",
            "--others",
            "--exclude-standard",
            # Python writes bytecode next to the scripts the build runs
            "--exclude=__pycache__",
            "--exclude=*.pyc",
            "-z",
        )
    except (OSError, subprocess.CalledProcessError):
        return ""

    build = build.resolve()
    paths = []
    for name in untracked.split(b"\0"):
        path = top / name.decode()
        if name and not path.resolve().is_relative_to(build):
            paths.append(path)

    if not diff and not paths:
        return f"git-tree-{tree}"

    digest = hashlib.sha256(diff)
    for path in sorted(paths):
        digest.update(b"\0" + str(path.relative_to(top)).encode() + b"\0")
        if path.is_symlink():
            digest.update(str(path.readlink()).encode())
        else:
            digest.update(hashlib.sha256(path.read_bytes()).digest())
    return f"git-tree-{tree}-dirty-{digest.hexdigest()[:16]}"


def main():
    source, build, *outputs = sys.argv[1:]
    content = (
        "# Generated by write-source-id.py\n"
        f'SOURCE_ID = "{source_id(Path(source), Path(build))}"\n'
    )
    for output in map(Path, outputs):
        if not output.exists() or output.read_text() != content:
            output.parent.mkdir(parents=True, exist_ok=True)
            output.write_text(content)


if __name__ == "__main__":
    main()
