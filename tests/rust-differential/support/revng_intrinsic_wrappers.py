"""Write LLVM IR wrappers for the LLVM intrinsics rev.ng declares as C helpers.

rev.ng's C backend emits a call to llvm.<name>.<type> as a call to a helper
named with the dots replaced by underscores and declares it in helpers.h. The
PTML form of that header keeps the original intrinsic name, so each wrapper
calls the named intrinsic itself and LLVM supplies its semantics.

Every declaration is checked against the intrinsic's signature here, because
zig's bundled clang compiles IR input without running the LLVM verifier.
"""

import argparse
import html
import re
from pathlib import Path

INTRINSIC = re.compile(r'data-location-definition="/helper-function/(llvm\.[^"]+)"')
DECLARATION = re.compile(r"(\w+) (\w+)\(([^)]*)\);")
C_TYPE = re.compile(r"(?:generic|u?int|number|pointer_or_number)(8|16|32|64|128)_t")

# Supported families and their operand counts. The result and every operand
# share the overloaded integer type, except the flags below.
OPERANDS = {
    "llvm.bswap": 1,
    "llvm.bitreverse": 1,
    "llvm.ctpop": 1,
    "llvm.abs": 2,
    "llvm.ctlz": 2,
    "llvm.cttz": 2,
    "llvm.umin": 2,
    "llvm.umax": 2,
    "llvm.smin": 2,
    "llvm.smax": 2,
    "llvm.uadd.sat": 2,
    "llvm.usub.sat": 2,
    "llvm.sadd.sat": 2,
    "llvm.ssub.sat": 2,
    "llvm.ushl.sat": 2,
    "llvm.sshl.sat": 2,
    "llvm.fshl": 3,
    "llvm.fshr": 3,
}
# These families end with an i1 flag LLVM requires to be a constant. The flag,
# when true, only turns some results into poison, so the wrappers pass false,
# which defines those results and agrees with the true form wherever that form
# is defined. The helper's C argument for it is ignored.
FLAGGED = {"llvm.abs", "llvm.ctlz", "llvm.cttz"}


def declarations(ptml):
    """Yield (intrinsic, result type, parameter types) from a helpers.h.ptml."""
    for line in ptml.splitlines():
        match = INTRINSIC.search(line)
        if not match:
            continue
        plain = html.unescape(re.sub(r"<[^>]+>", "", line)).strip()
        parsed = DECLARATION.fullmatch(plain)
        if not parsed:
            raise ValueError(f"unparsed intrinsic helper declaration: {plain!r}")
        result, name, parameters = parsed.groups()
        intrinsic = match[1]
        if name != intrinsic.replace(".", "_"):
            raise ValueError(f"helper {name} does not name intrinsic {intrinsic}")
        parameters = [p.strip() for p in parameters.split(",") if p.strip()]
        yield intrinsic, result, tuple(parameters)


def width(c_type):
    match = C_TYPE.fullmatch(c_type)
    if not match:
        raise ValueError(f"unsupported intrinsic helper type {c_type}")
    return int(match[1])


def wrapper(intrinsic, result, parameters):
    family, overload = intrinsic.rsplit(".", 1)
    if family not in OPERANDS:
        raise ValueError(f"unsupported intrinsic {intrinsic}")
    bits = width(result)
    values = parameters[:-1] if family in FLAGGED else parameters
    if (
        overload != f"i{bits}"
        or len(parameters) != OPERANDS[family]
        or any(width(p) != bits for p in values)
        or (family == "llvm.bswap" and bits % 16)
    ):
        raise ValueError(f"helper signature does not fit {intrinsic}")
    kind = f"i{bits}"
    arguments = [f"{kind} %{i}" for i in range(len(values))]
    operands = list(arguments)
    if family in FLAGGED:
        operands.append("i1 false")
        arguments.append(f"i{width(parameters[-1])} %flag")
    declared = ", ".join(o.split()[0] for o in operands)
    return (
        f"declare {kind} @{intrinsic}({declared})\n\n"
        f"define {kind} @{intrinsic.replace('.', '_')}({', '.join(arguments)}) {{\n"
        f"  %result = call {kind} @{intrinsic}({', '.join(operands)})\n"
        f"  ret {kind} %result\n"
        "}\n"
    )


def module(ptml_texts):
    """Return the IR module for every intrinsic declared in the given headers."""
    found = {}
    for text in ptml_texts:
        for intrinsic, result, parameters in declarations(text):
            if found.setdefault(intrinsic, (result, parameters)) != (
                result,
                parameters,
            ):
                raise ValueError(f"conflicting declarations of {intrinsic}")
    if not found:
        return None
    header = "; Generated by revng_intrinsic_wrappers.py from rev.ng helper headers.\n"
    return "\n".join([header, *(wrapper(i, *found[i]) for i in sorted(found))])


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("headers", nargs="+", type=Path, help="helpers.h.ptml files")
    parser.add_argument("-o", "--output", type=Path, required=True)
    args = parser.parse_args()
    text = module(path.read_text() for path in args.headers)
    if text is None:
        parser.error("the headers declare no LLVM intrinsic helpers")
    args.output.write_text(text)


if __name__ == "__main__":
    main()
